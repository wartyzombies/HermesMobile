# 2. Generated param/result structs for each target method
for method_name, (param_name, result_name) in target_param_types.items():
    param_schema = schemas.get(param_name) or {}
    result_schema = schemas.get(result_name) or {}

    # Build struct(s) if needed
    lines = []
    if param_schema:
        lines.append(f"/// Parameter for '{method_name}'\npublic struct {param_name}: Codable, Sendable {{")
        # If the schema is an object with properties
        if "properties" in param_schema:
            for field, field_schema in param_schema["properties"].items():
                swift_type_name = swift_type(schema=field_schema)
                # Optional by default (omit from required)
                optional = field not in param_schema.get("required", [])
                lines.append(f"    public let {field}: {swift_type_name}{'?' if optional else ''}")
        lines.append("}")
        lines.append("")
    if result_schema:
        lines.append(f"/// Result type for '{method_name}'")
        if "properties" in result_schema:
            lines.append(f"public struct {result_name}: Codable, Sendable {{")
            for field, field_schema in result_schema["properties"].items():
                swift_type_name = swift_type(schema=field_schema)
                optional = field not in result_schema.get("required", [])
                lines.append(f"    public let {field}: {swift_type_name}{'?' if optional else ''}")
            lines.append("}")
            lines.append("")

    # Write to a combined file to keep imports simple
    with open(OUT_DIR / "HermesGatewayClient.swift", "a") as f:
        f.write("\n".join(lines) + "\n")

