#!/usr/bin/env python3
"""Generate Swift HermesGatewayClient (wrapper) for the tui_gateway JSON-RPC.

We pull the OpenRPC spec once and emit a Swift file with typed request/result
structures for a subset of useful methods and a thin WebSocket connector.

We deliberately keep the generated shapes simple: Swift `Codable` and `Sendable`,
and we import the autogenerated `GeneratedModels` (Models.swift, OpenEnums.swift,
Methods.swift, Notifications.swift).

The purpose is to have a typed, ergonomic client you can build the iOS view
on top of, not a 1:1 code generator for the entire wire contract.
"""

from __future__ import annotations
import json, os, re, pathlib, sys
from pathlib import Path

CONTRACT = str(Path(__file__).resolve().parent.parent / "gateway-contract.openrpc.json")

spec = json.load(open(CONTRACT))
methods = spec.get("methods", [])
notifs = spec.get("x-notifications", [])
schemas = spec.get("components", {}).get("schemas", {})

# Names of the param/result shapes we want to expose via the client
target_param_types = {
    # Method -> (param_type, result_type)
    "promptSubmit": ("SubmitPromptParams", "PromptSubmitResult"),
    "sessionList": ("SessionListParams", "SessionListResult"),
    "sessionEventsSince": ("SessionEventsSinceParams", "SessionEventsSinceResult"),
    "sessionCreate": ("SessionCreateParams", "SessionCreateResult"),
    "sessionHistory": ("SessionHistoryParams", "SessionHistoryResult"),
    "sessionResume": ("SessionResumeParams", "SessionResumeResult"),
    "approvalRespond": ("ApprovalRespondParams", "ApprovalRespondResult"),
    "modelOptions": ("ModelOptionsParams", "ModelOptionsResult"),
    "sessionListRows": ("SessionListParams", "SessionListResult"),
    "sessionInfo": ("SessionInfoParams", "SessionInfoResult"),
    "configShow": ("ConfigShowParams", "ConfigShowResult"),
    "gatewayReady": ("GatewayReadyParams", "GatewayReadyPayload"),
    "sessionActivate": ("SessionActivateParams", "SessionActivateResult"),
    "sessionStatus": ("SessionStatusParams", "SessionStatusResult"),
}

# Map schema references to Swift types (matches GeneratedModels)
def swift_type(schema: dict) -> str:
    if "$ref" in schema:
        return schema["$ref"].rsplit("/", 1)[-1]
    t = schema.get("type")
    if t == "string":
        return "String"
    if t == "integer":
        return "Int64"
    if t == "number":
        return "Double"
    if t == "boolean":
        return "Bool"
    if t == "array":
        items = schema.get("items", {})
        if "anyOf" in items or "oneOf" in items:
            variants = list(items.get("anyOf") or items.get("oneOf") or [])
            if len(variants) != 1:
                return "[JSONValue]"
            return "[" + swift_type(schema=items) + "]"
        return "[" + swift_type(schema=items) + "]"
    if t == "object":
        return "JSONValue"
    # fallback
    return "JSONValue"

OUT_DIR = Path("/opt/data/profiles/coder/cache/scratch/HermesMobile/Sources/GatewayClient")
OUT_DIR.mkdir(parents=True, exist_ok=True)

